// 检索最匹配的问答
export function retrieveAnswer(query) {
  const q = query.toLowerCase();
  let best = null;
  let bestScore = 0;
  for (const item of mockQABank) {
    let score = 0;
    for (const kw of item.keywords) {
      if (q.includes(kw.toLowerCase())) score += 1;
    }
    if (score > bestScore) {
      bestScore = score;
      best = item;
    }
  }
  return { answer: best || defaultAnswer, matched: bestScore > 0 };
}
