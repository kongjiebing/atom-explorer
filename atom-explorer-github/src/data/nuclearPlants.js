// 辅助函数: 根据 id 获取集群
export function getClusterById(id) {
  return clusters.find((c) => c.id === id);
}

// 辅助函数: 根据 id 获取核电站
export function getPlantById(plantId) {
  for (const cluster of clusters) {
    const plant = cluster.plants.find((p) => p.id === plantId);
    if (plant) return { plant, cluster };
  }
  return null;
}
